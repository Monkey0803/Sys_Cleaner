#!/bin/zsh
set -euo pipefail

repo_root="${0:A:h:h}"
proof_root=$(/usr/bin/mktemp -d "$HOME/Library/Caches/SysCleaner-XcodeRebuildProof.XXXXXX")
cleanup() {
    case "$proof_root" in
        "$HOME"/Library/Caches/SysCleaner-XcodeRebuildProof.*)
            /usr/bin/swift -e 'import Foundation
                let target = URL(fileURLWithPath: CommandLine.arguments[1])
                var trashed: NSURL?
                try FileManager.default.trashItem(at: target, resultingItemURL: &trashed)' \
                "$proof_root" || echo "Could not move test directory to Trash: $proof_root" >&2
            ;;
    esac
}
trap cleanup EXIT

derived_root="$proof_root/DerivedData"
cache_names=(CompilationCache.noindex ModuleCache.noindex SDKStatCaches.noindex SDKExplicitPrecompiledModules)
generated_names=()

cd "$repo_root"
echo "Xcode version: $(xcodebuild -version | /usr/bin/tr '\n' ' ')"
xcodebuild -project SysCleaner.xcodeproj -scheme 'Sys Cleaner' -configuration Debug \
    -derivedDataPath "$derived_root" CODE_SIGNING_ALLOWED=NO build > "$proof_root/first-build.log" 2>&1 || {
    /usr/bin/tail -20 "$proof_root/first-build.log"
    exit 1
}

for cache_name in "${cache_names[@]}"; do
    cache_dir="$derived_root/$cache_name"
    if [[ ! -d "$cache_dir" || -z $(/usr/bin/find "$cache_dir" -type f -print -quit) ]]; then
        echo "Not generated by this build: $cache_name"
    else
        generated_names+=("$cache_name")
    fi
done
if (( ${#generated_names} == 0 )); then
    echo 'No candidate cache was generated; rebuildability is unverified.'
    exit 1
fi

/bin/mkdir "$proof_root/held"
for cache_name in "${generated_names[@]}"; do
    /bin/mv "$derived_root/$cache_name" "$proof_root/held/"
done

xcodebuild -project SysCleaner.xcodeproj -scheme 'Sys Cleaner' -configuration Debug \
    -derivedDataPath "$derived_root" CODE_SIGNING_ALLOWED=NO clean build > "$proof_root/rebuild.log" 2>&1 || {
    /usr/bin/tail -20 "$proof_root/rebuild.log"
    exit 1
}

for cache_name in "${generated_names[@]}"; do
    cache_dir="$derived_root/$cache_name"
    if [[ ! -d "$cache_dir" || -z $(/usr/bin/find "$cache_dir" -type f -print -quit) ]]; then
        echo "Clean build did not recreate $cache_name"
        exit 1
    fi
    echo "Recreated: $cache_name"
done

echo 'SymbolCache.noindex was not generated by this build; rebuildability remains unverified.'
